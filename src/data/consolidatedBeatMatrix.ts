/**
 * High-performance instant resolver for any input colony, sector, or landmark.
 * Guarantees zero duplicate results and returns the single definitive beat assignment.
 */
export function resolveAddressToConsolidatedBeat(
  query: string,
  preferredOfficeOrPincode?: string
): ConsolidatedBeatEntry | undefined {
  if (!query || !query.trim()) return undefined;
  const q = query.toLowerCase().trim();

  // 1. Direct Beat number match (e.g. "beat 2", "b2", "beat 33")
  const beatNumMatch = q.match(/\b(?:beat\s*|b)(\d+)\b/);
  if (beatNumMatch) {
    const num = parseInt(beatNumMatch[1], 10);
    // If it's a number 1-33, prefer Dadabari S.O. beat
    const foundDadabari = CONSOLIDATED_BEAT_MATRIX.find(
      (b) => b.deliveryOffice === 'Dadabari S.O.' && b.beatSeq === num
    );
    if (foundDadabari) return foundDadabari;

    const foundGeneral = CONSOLIDATED_BEAT_MATRIX.find((b) => b.beatSeq === num);
    if (foundGeneral) return foundGeneral;
  }

  // 2. Strict Delivery Office or Pincode filter if provided
  const candidatePool = preferredOfficeOrPincode
    ? CONSOLIDATED_BEAT_MATRIX.filter(
        (b) =>
          b.deliveryOffice.toLowerCase().includes(preferredOfficeOrPincode.toLowerCase()) ||
          b.pincode === preferredOfficeOrPincode
      )
    : CONSOLIDATED_BEAT_MATRIX;

  // 3. Colony match
  const colonyMatch = candidatePool.find((b) =>
    b.colonies.some((c) => c.toLowerCase().includes(q) || q.includes(c.toLowerCase()))
  );
  if (colonyMatch) return colonyMatch;

  // 4. Sector match
  const sectorMatch = candidatePool.find((b) =>
    b.sectors.some((s) => s.toLowerCase().includes(q) || q.includes(s.toLowerCase()))
  );
  if (sectorMatch) return sectorMatch;

  // 5. Landmark match
  const landmarkMatch = candidatePool.find((b) =>
    b.landmarks.some((l) => l.toLowerCase().includes(q) || q.includes(l.toLowerCase()))
  );
  if (landmarkMatch) return landmarkMatch;

  // 6. Global search across all strings
  return candidatePool.find(
    (b) =>
      b.coloniesFormatted.toLowerCase().includes(q) ||
      b.sectorsFormatted.toLowerCase().includes(q) ||
      b.landmarksFormatted.toLowerCase().includes(q) ||
      (b.staffId && b.staffId.toLowerCase().includes(q)) ||
      b.assignedPostmanName.toLowerCase().includes(q)
  );
}
